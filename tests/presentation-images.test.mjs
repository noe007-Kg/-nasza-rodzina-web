import test from 'node:test';
import assert from 'node:assert/strict';
import { sanitizePresentationImage, managePresentationImageAction } from '../server/presentation-images.mjs';
const png = Buffer.from([137,80,78,71,13,10,26,10]);
const path = 'quick-products/actor/synthetic.png';
function fixture(changes = {}) {
  const profile = { active:true, canLogin:true, role:'parent', familyId:'family-test', ...changes };
  const effects = [];
  const metadata = { name:path, size:String(png.length), contentType:'image/png', generation:'7', metageneration:'3', metadata:{ firebaseStorageDownloadTokens:'SYNTHETIC_TOKEN', custom:'keep' } };
  const file = { getMetadata:async()=>[metadata], download:async()=>[png], setMetadata:async(value,options)=>{effects.push({value,options});Object.assign(metadata,value);} };
  return { profile, metadata, file, effects, context:{ uid:'actor', profile:{...profile}, db:{collection:()=>({doc:()=>({get:async()=>({data:()=>profile})})})},
    bucket:{file:()=>file} } };
}
test('presentation images verify original bytes and revoke autogenerated tokens with version preconditions', async()=>{
  const f=fixture(); assert.deepEqual(await sanitizePresentationImage(f.context,path),{path,familyId:'family-test'});
  assert.equal(f.effects[0].value.metadata.firebaseStorageDownloadTokens,null);
  assert.equal(f.effects[0].value.metadata.custom,'keep'); assert.equal(f.effects[0].value.cacheControl,'private, no-store');
  assert.deepEqual(f.effects[0].options,{ifGenerationMatch:'7',ifMetagenerationMatch:'3'});
  assert.ok(!JSON.stringify(f.effects).includes('SYNTHETIC_TOKEN'));
});
test('foreign paths and missing/legacy/disabled household deny before any Storage access', async()=>{
  for(const change of [{familyId:undefined},{familyId:'__legacy__'},{disabled:true},{active:false}]) {
    const f=fixture(change); f.context.bucket.file=()=>{throw new Error('UNEXPECTED_STORAGE_READ');};
    await assert.rejects(sanitizePresentationImage(f.context,path),{code:'STORAGE_HOUSEHOLD_REQUIRED'}); assert.equal(f.effects.length,0);
  }
  const f=fixture(); await assert.rejects(sanitizePresentationImage(f.context,'quick-products/foreign/synthetic.png'),{code:'STORAGE_IMAGE_FORBIDDEN'});
  await assert.rejects(managePresentationImageAction(f.context,{operation:'finalizeProductImage',path,familyId:'forged'}));
});
test('wrong file type/signature/size and household changes during download never publish a path or remove tokens', async()=>{
  for(const change of [{contentType:'application/pdf'},{size:'9000000'},{size:'7'},{generation:'bad'}]) {
    const f=fixture(); Object.assign(f.metadata,change); await assert.rejects(sanitizePresentationImage(f.context,path)); assert.equal(f.effects.length,0);
  }
  const f=fixture(); f.file.download=async()=>{f.profile.familyId='foreign-family';return[png];};
  await assert.rejects(sanitizePresentationImage(f.context,path),{code:'STORAGE_HOUSEHOLD_REQUIRED'}); assert.equal(f.effects.length,0);
});
test('re-finalization cannot adopt an existing household or uploader binding after a profile move', async()=>{
  for (const binding of [{familyId:'previous-household'},{familyId:'__legacy__'},{familyId:null},{uploaderUid:'another-uploader'}]) {
    const f=fixture(); Object.assign(f.metadata.metadata,binding);
    f.file.download=async()=>{throw new Error('UNEXPECTED_DOWNLOAD');};
    await assert.rejects(sanitizePresentationImage(f.context,path),{code:'STORAGE_IMAGE_FORBIDDEN'});
    assert.equal(f.effects.length,0);
    assert.equal(f.metadata.metadata.firebaseStorageDownloadTokens,'SYNTHETIC_TOKEN');
  }
  const f=fixture();Object.assign(f.metadata.metadata,{familyId:'family-test',uploaderUid:'actor'});
  assert.deepEqual(await sanitizePresentationImage(f.context,path),{path,familyId:'family-test'});
});
test('silent token revocation failure and object replacement cannot publish a protected image path',async()=>{
  for(const replacement of [false,true]){
    const f=fixture();f.file.setMetadata=async value=>{
      if(replacement){Object.assign(f.metadata,value);f.metadata.generation='8';}
    };
    await assert.rejects(sanitizePresentationImage(f.context,path),{code:'STORAGE_IMAGE_NOT_READY'});
  }
});
